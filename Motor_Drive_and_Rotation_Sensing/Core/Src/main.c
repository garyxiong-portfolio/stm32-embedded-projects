/*
 * Called when an enabled GPIO EXTI interrupt occurs.
 * Only count pulses belonging to the RPM sensor.
 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == RPM_Tick_Pin)
  {
    rpm_tick_count++;
  }
}

/*
 * Report the cumulative pulse count from the main program.
 * UART transmission is kept outside the interrupt callback.
 */
static void RPM_Report(void)
{
  char message[64];

  sprintf(message,
          "RPM ticks: %lu\r\n",
          (unsigned long)rpm_tick_count);

  HAL_UART_Transmit(&huart2,
                    (uint8_t *)message,
                    (uint16_t)strlen(message),
                    100);
}

